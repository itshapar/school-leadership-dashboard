export const ALL_EMOJI: EmojiItem[] = EMOJI_CATEGORIES.flatMap((c) => c.items);

/**
 * Пошук за українськими ключами: збіг за початком будь-якого слова, а не за
 * підрядком будь-де. "кіт" знаходить "кіт", "кішка", але не "закінчення";
 * так результати лишаються передбачуваними при короткому запиті.
 */
export function searchEmoji(query: string): EmojiItem[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  // Якщо вставили саме емодзі, а не текст, шукати нема чого.
  if (!/[a-zа-яіїєґ0-9]/i.test(q)) return [];
  return ALL_EMOJI.filter((item) =>
    item.keys.split(" ").some((word) => word.startsWith(q))
  );
}
