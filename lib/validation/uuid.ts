import { z } from "zod";

/**
 * UUID у тому вигляді, в якому вони реально лежать у нашій базі, а не
 * строго за RFC 4122.
 *
 * Чому не `z.string().uuid()`: у Zod 4 ця перевірка звіряє ще й біти
 * версії та варіанту — версія мусить бути 1..8, а варіант 8/9/a/b. Класи,
 * засіяні на ранніх етапах, мають навмисно передбачувані id
 * (`11111111-0000-0000-0000-00000000000N`), де і версія, і варіант — нулі.
 * Формально це не UUID жодної версії, і Zod відкидав такі запити з
 * «Invalid request data», хоча тип `uuid` у Postgres приймає їх спокійно.
 *
 * Наслідок був мовчазний і дорогий (живий фідбек): у класах 7А-7Е журнал
 * не зберігав зірки (клітинка на секунду мінялась і відкочувалась назад),
 * не створювався урок, не проходили нарахування. Тобто ламалось усе, що
 * шле class_id в /api/admin/*.
 *
 * Тут перевіряємо саме форму рядка: 8-4-4-4-12 шістнадцяткових символів.
 * Захист від підстановки чужого id це не послаблює — ним і далі займаються
 * assertClassOwnership та RLS, а не формат рядка.
 */
export const uuidLike = z
  .string()
  .regex(
    /^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$/,
    "Invalid UUID"
  );
