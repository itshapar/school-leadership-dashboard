-- ============================================================================
-- 04_legacy_codes.sql — Етап 8, вимога 4: старі публічні коди класів.
--
-- РІШЕННЯ ВЛАСНИКА (2026-08-20): прибрати.
--
-- Контекст. До Етапу 1 код класу був 4-значним числом — простір перебору
-- 10 000. Етап 1 дав 10-символьні коди (~8×10¹⁴), але старий код лишили
-- живим у classes.legacy_code як redirect, щоб не ламати роздані пам'ятки.
-- Поки він живий, уся робота Етапу 1 не дає нічого: стара двері поруч
-- відчинена, і за пів години перебору видно публічну сторінку будь-якого
-- класу в системі.
--
-- Що бачить дитина зі старою пам'яткою після цього скрипта: НЕ 404, а екран
-- «Цей код більше не діє — візьми новий у вчителя» (components/LegacyCodeNotice).
-- Екран показується для будь-якого 4-значного коду, бо перевіряється лише
-- ФОРМАТ — інакше він став би оракулом «такий клас є / такого немає».
--
-- ⚠️ ПЕРЕДУМОВА: фронтенд із LegacyCodeNotice має бути ЗАДЕПЛОЄНИЙ. Інакше
-- учні впруться в голий 404.
--
-- Зворотність: коди зберігаються нижче в NOTICE перед стиранням — за потреби
-- їх можна повернути вручну. Але сенсу в цьому немає: правильна реакція на
-- «учень не може зайти» — видати новий код, а не воскрешати старий.
-- ============================================================================

BEGIN;

-- 1. Друкуємо, що саме стираємо (лишиться в логах сесії).
DO $$
DECLARE r record;
BEGIN
  FOR r IN SELECT name, public_code, legacy_code FROM public.classes
           WHERE legacy_code IS NOT NULL ORDER BY name
  LOOP
    RAISE NOTICE 'Клас % : старий код % → новий %', r.name, r.legacy_code, r.public_code;
  END LOOP;
END $$;

-- 2. Стираємо.
UPDATE public.classes SET legacy_code = NULL WHERE legacy_code IS NOT NULL;

COMMIT;

-- 3. Перевірка: має бути 0.
SELECT count(*) AS classes_with_legacy_code
FROM public.classes WHERE legacy_code IS NOT NULL;
