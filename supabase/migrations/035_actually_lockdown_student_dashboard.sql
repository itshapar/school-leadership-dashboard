-- 035_actually_lockdown_student_dashboard.sql
-- Реально застосовано зараз (Етап 9.12, живий фідбек): міграція 024 існувала
-- в репозиторії з умовою "застосувати після того, як фронтенд з учнівськими
-- сесіями задеплоєно і PIN-и роздані" — обидві умови вже виконані вже давно,
-- але сам REVOKE так ніколи й не був застосований до бази (той самий клас
-- бага, що й із міграцією 033 — файл написаний, коміт стверджував, що
-- застосовано, база каже інше).
--
-- Наслідок: public_student_dashboard(text, uuid) був виконуваний і для anon,
-- і для authenticated. Будь-хто, хто знає код класу й student_id (UUID)
-- конкретного учня, міг переглянути повний персональний дашборд ЦЬОГО учня
-- (зірки, ранг, історію нарахувань) без жодного PIN. Для authenticated —
-- гірше: функція SECURITY DEFINER не перевіряє teacher_id = auth.uid(),
-- тож будь-який вчитель міг переглянути учня ІНШОГО вчителя.
--
-- Фронтенд уже готовий до цього: /class/[code]/student/[id] і так робить
-- redirect на /class/[code]/me, коли RPC повертає NULL — застосування цієї
-- міграції нічого не ламає, лише закриває дірку.
-- ============================================================================

BEGIN;

REVOKE EXECUTE ON FUNCTION public.public_student_dashboard(text, uuid) FROM PUBLIC, anon, authenticated;

COMMIT;
