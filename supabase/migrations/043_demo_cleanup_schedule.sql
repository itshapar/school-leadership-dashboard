-- ============================================================================
-- 043_demo_cleanup_schedule.sql
-- Автоматичне прибирання демо: pg_cron щогодини.
--
-- Розклад живе в самій базі, а не в зовнішньому планувальнику (Vercel Cron,
-- Edge Function): прибирання не має залежати ні від деплою застосунку, ні від
-- того, чи хтось відкрив сайт, ні від зовнішнього ключа, який колись протухне.
-- Це найкоротший шлях між обіцянкою «демо зникає разом із сесією» і тим, що
-- реально відбувається.
--
-- Поріг 6 годин: сесія гостя живе довше за будь-який реальний огляд продукту,
-- тож нікого не викине посеред перегляду, і водночас база не встигає обрости.
--
-- Застосовано до прод-БД 1 вересня 2026. Перевірено тимчасовим завданням із
-- розкладом «щохвилини»: два запуски поспіль зі статусом succeeded, після чого
-- тимчасове завдання знято.
-- ============================================================================

BEGIN;

CREATE EXTENSION IF NOT EXISTS pg_cron;

-- Ідемпотентність: повторне застосування не плодить дублів.
SELECT cron.unschedule(jobid) FROM cron.job WHERE jobname = 'demo-cleanup';

-- О 17-й хвилині кожної години, а не о нульовій: у нульову хвилину в Postgres
-- зазвичай юрмляться інші періодичні задачі.
SELECT cron.schedule(
  'demo-cleanup',
  '17 * * * *',
  $$SELECT public.delete_stale_demo_users('6 hours')$$
);

COMMIT;
