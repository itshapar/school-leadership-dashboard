-- ============================================================================
-- 048_teacher_parallels_toggle.sql — вимикач паралелей у профілі вчителя
--
-- Паралель (номер класу 1–12) має сенс у школі. У закладах, де класів-паралелей
-- немає (студії, курси, гуртки — там просто групи), поле «Паралель» лише
-- заважає: воно обов'язкове при створенні класу й породжує зайві фільтри в
-- кабінеті, рейтингу й на дашборді.
--
-- Прапорець живе в профілі вчителя, бо це властивість закладу, а не окремого
-- класу. Дані не чіпаємо: вимкнення лише ховає поле й фільтри, наявні
-- classes.parallel_id лишаються на місці й повертаються, якщо ввімкнути назад.
--
-- Адитивна міграція: колонка з DEFAULT true, тож усі наявні акаунти
-- продовжують працювати рівно як раніше.
-- ============================================================================

BEGIN;

ALTER TABLE public.teacher_profiles
  ADD COLUMN IF NOT EXISTS parallels_enabled boolean NOT NULL DEFAULT true;

COMMENT ON COLUMN public.teacher_profiles.parallels_enabled IS
  'Чи показувати паралелі (номер класу 1–12) у створенні класу й фільтрах. false — заклад без паралелей.';

-- Гранти на teacher_profiles — explicit-only, поколонково (патерн 021).
GRANT UPDATE (parallels_enabled) ON public.teacher_profiles TO authenticated;

COMMIT;
