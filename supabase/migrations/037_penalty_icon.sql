-- ---------------------------------------------------------------------------
-- 037: іконка типу «Штраф» — ⛔ замість ⚡ (живий фідбек).
--
-- Блискавка читалась як щось швидке чи бонусне, а не як штраф. Знак «в'їзд
-- заборонено» однозначний і червоний, тобто одразу відрізняється від
-- подарунка «Бонус» у тому ж списку.
--
-- Змінюємо і системний шаблон (нові класи), і вже наявні типи в класах
-- учителів. Дані, історія нарахувань і будь-яка логіка не зачіпаються:
-- icon — суто підпис для інтерфейсу.
-- ---------------------------------------------------------------------------

UPDATE public.config_templates
SET payload = jsonb_set(
  payload,
  '{entry_types}',
  (
    SELECT jsonb_agg(
      CASE
        WHEN et->>'name' = 'Штраф' THEN jsonb_set(et, '{icon}', '"⛔"')
        ELSE et
      END
    )
    FROM jsonb_array_elements(payload->'entry_types') AS et
  )
)
WHERE is_system = true
  AND payload ? 'entry_types';

UPDATE public.entry_types
SET icon = '⛔'
WHERE name = 'Штраф'
  AND icon = '⚡';
